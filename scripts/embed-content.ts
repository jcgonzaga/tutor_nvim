import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { readContentInput } from "../apps/api/src/content";

// Regenerates the copy of content/ that the API embeds (see loadRuntimeContent). Run after editing
// content/; the API test suite fails while the two differ.
const target = fileURLToPath(new URL("../apps/api/src/content.embedded.ts", import.meta.url));
const header = `// GENERATED by \`pnpm content:embed\` from content/. Do not edit by hand.\n`;
const body = `import type { ContentInput } from "@tutor-nvim/exercise-schema";\n\nexport const embeddedContent: ContentInput = ${JSON.stringify(readContentInput(), null, 1)};\n`;
writeFileSync(target, header + body);
console.log(`wrote ${target}`);
